const normalize = (name) => name.replace(/\s/g, '');
const matchEntry = (name, entries) => Object.entries(entries)
  .sort(([a], [b]) => b.length - a.length)
  .find(([key]) => name.includes(key))?.[1];

export function getProductDescription(product) {
  const name = normalize(product.name);
  if (['fragrances', 'exclusive'].includes(product.catalogCategory)) {
    return matchEntry(name, FRAGRANCES);
  }
  if (product.catalogCategory === 'bath-body') {
    const care = matchEntry(name, BODY_CARE);
    if (care) return `${care}${name.includes('리필') ? ' 기존 용기에 채워 사용하는 리필 제품입니다.' : ''}`;
    const scent = matchEntry(name, FRAGRANCES) || matchEntry(name, HOME_SCENTS);
    const type = name.includes('핸드크림') ? '손을 위한 향기로운 크림으로 만나보세요.'
      : name.includes('로션') ? '손과 몸을 돌보는 로션으로 향의 여운을 즐겨보세요.'
        : name.includes('바디밤') ? '바디 밤으로 몸을 돌보며 향을 즐겨보세요.'
          : name.includes('애프터선') ? '햇볕을 즐긴 뒤 사용하는 바디 밀키 젤입니다.'
            : name.includes('바디미스트') ? '몸에 가볍게 뿌리는 미스트로 만나보세요.'
              : name.includes('샤워오일') ? '샤워 오일로 매일의 세정 시간을 향기롭게 바꾸어 보세요.'
                : name.includes('솝') ? '고체 비누로 매일의 세정 시간을 향기롭게 즐겨보세요.'
                  : name.includes('샤워폼') ? '샤워 폼으로 향기로운 바디 세정 시간을 즐겨보세요.'
                    : '손과 몸을 씻는 클렌징 젤로 만나보세요.';
    return scent ? `${scent.split('. ')[0]}. ${type}` : undefined;
  }
  if (product.catalogCategory === 'candles-home') {
    if (name.includes('미니캔들세트')) return '작은 캔들 다섯 개로 여러 향을 만나보는 세트입니다. 그날의 기분과 공간에 어울리는 향을 골라, 서로 다른 분위기를 즐겨보세요.';
    if (name.includes('스몰캔들세트')) return '베이, 휘기에, 로즈를 함께 만나는 스몰 캔들 세트입니다. 열매와 나무, 꽃이 그리는 세 가지 풍경을 일상에서 즐겨보세요.';
    if (name.includes('라드로게리')) return '집 안을 돌보는 라 드로게리 컬렉션의 캔들입니다. 일상의 공간에 향을 더해 편안한 분위기를 만들어 보세요.';
    const scent = matchEntry(name, HOME_SCENTS);
    return scent ? `${scent} ${name.includes('리필') ? '프리미엄 캔들 용기에 채워 향의 시간을 이어가는 리필입니다.' : '불을 밝히고 공간에 펼쳐지는 향의 풍경을 즐겨보세요.'}` : undefined;
  }
  if (product.catalogCategory === 'home-decor') {
    if (name.includes('유리병')) return '딥티크의 홈 프래그런스를 담는 리드 디퓨저 유리 용기입니다. 원하는 향의 리필과 함께 나만의 공간에 어울리는 향의 오브제를 완성해 보세요.';
    if (name.includes('마개')) return '100ml와 200ml 리드 디퓨저 용기를 위한 마개입니다. 유리 용기와 함께 사용하는 전용 액세서리로 디퓨저의 형태를 완성합니다.';
    if (name.includes('세라믹')) return '시더우드 향을 담은 옷장용 세라믹입니다. 울과 섬세한 소재의 옷을 보관하는 공간에 은은한 나무 향을 더합니다.';
    if (name.includes('탈취용')) return '생활 공간의 냄새 관리를 위한 룸 스프레이입니다. 집 안을 돌보는 일상에 향기로운 마무리를 더해 보세요.';
    const scent = matchEntry(name, HOME_SCENTS);
    const type = name.includes('차량용') ? '차량 안에서 즐기는 디퓨저 세트로, 이동하는 시간에도 향을 더합니다.'
      : name.includes('캡슐') ? '디퓨저와 함께 사용하는 향기 캡슐로 일상에 향을 더합니다.'
        : name.includes('오발') ? '향을 담은 오벌 오브제로 작은 공간에 은은한 분위기를 더합니다.'
          : name.includes('룸스프레이') ? '룸 스프레이로 원하는 순간 공간의 분위기를 바꾸어 보세요.'
            : name.includes('리필') ? '해당 디퓨저에 채워 향의 시간을 이어가는 리필입니다.'
              : '모래시계 형태의 디퓨저로 공간에 향과 아름다운 오브제를 더합니다.';
    return scent ? `${scent} ${type}` : undefined;
  }
  return undefined;
}
